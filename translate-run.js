const files = [];
function walk(dir) {
  const list = fs.readdirSync(dir);
  list.forEach(f => {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (p.endsWith('.tsx') || p.endsWith('.ts')) files.push(p);
  });
}
walk('./src');

let totalReplaced = 0;

files.forEach(f => {
  let content = fs.readFileSync(f, 'utf8');
  let replacedCount = 0;
  
  // This regex matches `t( 'ar', 'en' )` ignoring multiline if they aren't separated by newlines within the match logic, but handles some spaces
  // We use [\s\S]*? for spaces to handle newlines
  const regex = /t\(\s*(['"`])(.*?)\1\s*,\s*(['"`])(.*?)\3\s*\)/g;
  
  const newContent = content.replace(regex, (match, q1, ar, q2, en) => {
    // If it already has 3 args, it wouldn't match this regex exactly (actually it might if there's a third arg but regex only captures two). 
    // Let's refine regex to ensure it only matches exactly 2 string arguments
    return match;
  });

  // A better regex that explicitly matches `t("ar", "en")` and NOT `t("ar", "en", "ku")`.
  // `t(\s*['"`]ar['"`]\s*,\s*['"`]en['"`]\s*)`
  const betterRegex = /t\(\s*(['"`])([^'"`\\]*(?:\\.[^'"`\\]*)*)\1\s*,\s*(['"`])([^'"`\\]*(?:\\.[^'"`\\]*)*)\3\s*\)/g;

  content = content.replace(betterRegex, (match, q1, ar, q2, en) => {
    const ku = map[ar] || ar;
    replacedCount++;
    totalReplaced++;
    // if using template literals with ${}, we should use backticks for ku too
    const kuQuote = (ku.includes('${') || q1 === '`') ? '`' : "'";
    return `t(${q1}${ar}${q1}, ${q2}${en}${q2}, ${kuQuote}${ku.replace(/'/g, "\\'")}${kuQuote})`;
  });

  if (replacedCount > 0) {
    fs.writeFileSync(f, content, 'utf8');
    console.log(`Updated ${f} (${replacedCount} replacements)`);
  }
});

console.log(`\nTotal strings translated: ${totalReplaced}`);
